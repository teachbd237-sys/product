export function mergeSettings(rows) {
  const out = { ...DEFAULT_SETTINGS }
  for (const r of rows || []) {
    if (!(r.key in DEFAULT_SETTINGS)) continue
    const v = r.value
    // খালি লেখা Default-কে ওভাররাইড করবে না (লোগো/লিংক ছাড়া — ওগুলোর Default-ই খালি)
    if (v === null || v === undefined) continue
    if (typeof v === 'string' && v.trim() === '' && DEFAULT_SETTINGS[r.key] !== '') continue
    if (Array.isArray(v) && v.length === 0) continue
    out[r.key] = v
  }
  return out
}
